---- KEYBINDINGS ----
---------------------

local apps = require("apps")

local terminal, fileManager, launcher, browser, runner =
	apps.terminal, apps.fileManager, apps.launcher, apps.browser, apps.runner

local mainMod = "SUPER" -- Sets "Windows" key as main modifier
local secondMod = "SUPER + SHIFT"

-- Example binds, see https://wiki.hypr.land/Configuring/Basics/Binds/ for more
hl.bind(mainMod .. " + T", hl.dsp.exec_cmd(terminal))
local closeWindowBind = hl.bind(mainMod .. " + Q", hl.dsp.window.close())

-- closeWindowBind:set_enabled(false)
-- Matches the SDDM greeter's own SUPER+M convention (its
-- autogenerated config maps SUPER+M to exit there too) - a different
-- session/config entirely, but keeping the muscle memory consistent.
-- hl.dsp.exit() called directly here, not wrapped in exec_cmd/
-- hyprctl - that was the previous bug: embedding "hl.dsp.exit()" as
-- a literal string inside a hyprctl dispatch call isn't valid there,
-- so the old bind likely never worked at all.
hl.bind(mainMod .. " + M", hl.dsp.exit())
hl.bind(mainMod .. " + F", hl.dsp.exec_cmd(fileManager))
hl.bind(mainMod .. " + W", hl.dsp.exec_cmd("waypaper"))
hl.bind(mainMod .. " + L", hl.dsp.exec_cmd("hyprlock"))
hl.bind(secondMod .. " + L", hl.dsp.exec_cmd(
	"pkill -x wlogout >/dev/null 2>&1 || wlogout --buttons-per-row 5"
	.. " --margin-top 400 --margin-bottom 260 --margin-left 260 --margin-right 260"
	-- Reference-theme grid (config/wlogout/style.css). Tuned for a
	-- 1920x1080 panel; rescale roughly proportionally elsewhere.
))
hl.bind(mainMod .. " + period", hl.dsp.exec_cmd("rofimoji --action copy"))
hl.bind(mainMod .. " + P", hl.dsp.window.pseudo())
-- Bound to the script's absolute path, not the "hyprx-settings"
-- symlink name - Hyprland's exec environment doesn't reliably
-- inherit ~/.local/bin on PATH the way an interactive terminal
-- shell does, even though the symlink itself resolves fine when
-- typed directly. Same tilde-path approach already used by the
-- screenshot binds below.
hl.bind(mainMod .. " + I", hl.dsp.exec_cmd("~/.local/share/hyprx/scripts/settings-menu.sh"))
hl.bind(mainMod .. " + D", hl.dsp.exec_cmd("kitty --hold -e fastfetch"))
hl.bind(mainMod .. " + F5", hl.dsp.exec_cmd("~/.local/share/hyprx/scripts/power-profile-cycle.sh"))
hl.bind(mainMod .. " + F6", hl.dsp.exec_cmd("rog-control-center"))
hl.bind(secondMod .. " + Q", hl.dsp.exec_cmd("code ~/.config/hypr"))

-- hl.bind(mainMod .. " + J", hl.dsp.layout("togglesplit"))    -- dwindle only
hl.bind(mainMod .. " + B", hl.dsp.exec_cmd(browser))
hl.bind(mainMod .. " + Space", hl.dsp.exec_cmd(launcher))
hl.bind(secondMod .. " + Space", hl.dsp.exec_cmd(runner))

-- Move focus with mainMod + arrow keys
hl.bind(mainMod .. " + left", hl.dsp.focus({ direction = "left" }))
hl.bind(mainMod .. " + right", hl.dsp.focus({ direction = "right" }))
hl.bind(mainMod .. " + up", hl.dsp.focus({ direction = "up" }))
hl.bind(mainMod .. " + down", hl.dsp.focus({ direction = "down" }))

-- Move windows
hl.bind(secondMod .. " + left", hl.dsp.window.move({ direction = "left" }))
hl.bind(secondMod .. " + right", hl.dsp.window.move({ direction = "right" }))
hl.bind(secondMod .. " + up", hl.dsp.window.move({ direction = "up" }))
hl.bind(secondMod .. " + down", hl.dsp.window.move({ direction = "down" }))

-- Toggle Window
hl.bind(secondMod .. " + T", hl.dsp.window.float({ action = "toggle" }))
hl.bind(secondMod .. " + F", hl.dsp.window.fullscreen({ mode = "maximized", action = "toggle" }))

-- Screenshot
-- Print                 = fullscreen, save + copy
-- mainMod + Print        = region, save + copy
-- secondMod + Print      = region, open in swappy to annotate (swappy saves/copies itself)
hl.bind(
	"Print",
	hl.dsp.exec_cmd(
		[[mkdir -p ~/Pictures/Screenshots && f=~/Pictures/Screenshots/$(date +'%Y-%m-%d_%H-%M-%S').png && grim "$f" && wl-copy < "$f"]]
	)
)
hl.bind(
	mainMod .. " + Print",
	hl.dsp.exec_cmd(
		[[mkdir -p ~/Pictures/Screenshots && f=~/Pictures/Screenshots/$(date +'%Y-%m-%d_%H-%M-%S').png && grim -g "$(slurp)" "$f" && wl-copy < "$f"]]
	)
)
hl.bind(
	secondMod .. " + Print",
	hl.dsp.exec_cmd([[mkdir -p ~/Pictures/Screenshots && grim -g "$(slurp)" - | swappy -f -]])
)

-- Switch workspaces with mainMod + [0-9]
-- Move active window to a workspace with mainMod + SHIFT + [0-9]
for i = 1, 10 do
	local key = i % 10 -- 10 maps to key 0
	hl.bind(mainMod .. " + " .. key, hl.dsp.focus({ workspace = i }))
	hl.bind(secondMod .. " + " .. key, hl.dsp.window.move({ workspace = i }))
end

-- Example special workspace (scratchpad)
hl.bind(mainMod .. " + S", hl.dsp.workspace.toggle_special("magic"))
hl.bind(mainMod .. " + SHIFT + S", hl.dsp.window.move({ workspace = "special:magic" }))

-- Scroll through existing workspaces with mainMod + scroll
hl.bind(mainMod .. " + mouse_down", hl.dsp.focus({ workspace = "e+1" }))
hl.bind(mainMod .. " + mouse_up", hl.dsp.focus({ workspace = "e-1" }))

-- Move/resize windows with mainMod + LMB/RMB and dragging
hl.bind(mainMod .. " + mouse:272", hl.dsp.window.drag(), { mouse = true })
hl.bind(mainMod .. " + mouse:273", hl.dsp.window.resize(), { mouse = true })

-- Laptop multimedia keys for volume and LCD brightness
hl.bind(
	"XF86AudioRaiseVolume",
	hl.dsp.exec_cmd("wpctl set-volume -l 1 @DEFAULT_AUDIO_SINK@ 5%+"),
	{ locked = true, repeating = true }
)
hl.bind(
	"XF86AudioLowerVolume",
	hl.dsp.exec_cmd("wpctl set-volume @DEFAULT_AUDIO_SINK@ 5%-"),
	{ locked = true, repeating = true }
)
hl.bind(
	"XF86AudioMute",
	hl.dsp.exec_cmd("wpctl set-mute @DEFAULT_AUDIO_SINK@ toggle"),
	{ locked = true, repeating = true }
)
hl.bind(
	"XF86AudioMicMute",
	hl.dsp.exec_cmd("wpctl set-mute @DEFAULT_AUDIO_SOURCE@ toggle"),
	{ locked = true, repeating = true }
)
hl.bind("XF86MonBrightnessUp", hl.dsp.exec_cmd("brightnessctl -e4 -n2 set 5%+"), { locked = true, repeating = true })
hl.bind("XF86MonBrightnessDown", hl.dsp.exec_cmd("brightnessctl -e4 -n2 set 5%-"), { locked = true, repeating = true })

-- Requires playerctl
hl.bind("XF86AudioNext", hl.dsp.exec_cmd("playerctl next"), { locked = true })
hl.bind("XF86AudioPause", hl.dsp.exec_cmd("playerctl play-pause"), { locked = true })
hl.bind("XF86AudioPlay", hl.dsp.exec_cmd("playerctl play-pause"), { locked = true })
hl.bind("XF86AudioPrev", hl.dsp.exec_cmd("playerctl previous"), { locked = true })

